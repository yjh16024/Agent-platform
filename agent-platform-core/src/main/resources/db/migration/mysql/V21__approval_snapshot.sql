-- 工具审批：改前快照与回滚（sys_tool_approval 加两列）
--
-- 定位：把"智能体改文件"从"不可逆"变成"可撤销"。
-- 这是用户敢让它动自己代码的前提 —— 没有回滚，审批放行的每一条都是单向门。
--
-- 设计要点：
--  1) **快照以「审批」为单位**，不是"每个文件留一份 .bak"。
--     理由：用户的心智是"撤销刚才那次操作"，而一次批准可能改一个文件、
--     也可能新建一个文件 —— 单文件备份表达不了"这次操作整体是什么"。
--     快照目录约定为 `{agent-platform.agent.workspace.snapshot-dir}/{approvalId}/`，
--     按相对路径镜像原文件，所以不需要为每个文件单独建表。
--  2) **记录 snapshot_dir 而不是"有没有快照"的布尔值**：将来若把快照挪到别处
--     （如对象存储），有这一列才能定位；也便于排查"为什么这次没快照"。
--     为空表示这次操作没有产生快照（如：目标本来不存在，我们只记了"新建"标记 ——
--     那种情况回滚动作是"删除文件"，不需要字节内容）。
--  3) **rolled_back_at 用时间戳而非布尔**：既能判"是否已回滚"，又留下"什么时候回滚的"，
--     存储成本一样。且**允许为空**是必要的：绝大多数记录永远不会被回滚。
--  4) 回滚是**幂等保护**的：已有 rolled_back_at 的记录不允许再次回滚 ——
--     否则"恢复到某次快照"会被误解成"再执行一次当时的操作"。
--
-- 本文件与 h2 目录下的副本内容相同（H2 跑 MySQL 兼容模式），沿用 V12/V15~V20 的既有做法。
-- 注意：迁移一旦执行就不可修改（Flyway checksum），要改只能新建 V22。

ALTER TABLE sys_tool_approval ADD COLUMN snapshot_dir VARCHAR(500) NULL;
ALTER TABLE sys_tool_approval ADD COLUMN rolled_back_at DATETIME NULL;
